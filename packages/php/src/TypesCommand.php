<?php

declare(strict_types=1);

namespace Sti3bas\Rehearsal;

use BackedEnum;
use Closure;
use Illuminate\Console\Command;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use ReflectionFunction;
use ReflectionMethod;
use Throwable;

final class TypesCommand extends Command
{
    private ?string $inMemorySchema = null;

    private bool $inMemorySchemaAttempted = false;
    protected $signature = 'rehearsal:types {path : Destination .d.ts file} {--database= : Read columns from this configured connection}';

    protected $description = 'Generate TypeScript declarations for this application’s Rehearsal configuration';

    public function handle(Operations $operations, Factories $registry, Schedules $schedules): int
    {
        $path = $this->argument('path');
        if (! str_ends_with($path, '.d.ts')) {
            $this->error('The destination must end in .d.ts.');

            return self::FAILURE;
        }

        $allFactories = $registry->all();
        $aliasesByClass = [];
        foreach ($allFactories as $alias => $definition) {
            if (isset($definition['model']) && is_string($definition['model'])) {
                $aliasesByClass[$definition['model']] ??= $alias;
            }
        }
        $usedHelpers = [];
        $factories = [];
        foreach ($allFactories as $alias => $definition) {
            $factories[$alias] = $this->factory($definition, $registry->states($definition), $registry->definitionKeys($definition), $aliasesByClass, $usedHelpers);
        }
        $calls = [];
        foreach ($operations->typeDefinitions() as $name => $definition) {
            $types = $definition['types'] ?? [];
            $handler = $definition['handler'];
            $methodName = is_string($definition['method'] ?? null) ? $definition['method'] : '__invoke';
            $reflection = $handler instanceof Closure ? new ReflectionFunction($handler) : new ReflectionMethod($handler, $methodName);
            $input = $types['input'] ?? $this->operationInput($reflection, $definition['rules'], $aliasesByClass, $usedHelpers);
            $output = $types['output'] ?? PhpDocTypes::returnType($reflection, $aliasesByClass, $usedHelpers);
            $calls[$name] = "{ input: $input; output: $output }";
        }
        $artisan = $this->artisanTypes();
        $schema = $this->shape([
            'factories' => $this->shape($factories),
            'operations' => $this->shape($calls),
            'artisan' => $this->shape($artisan),
            'schedules' => $this->literals(array_keys($schedules->all())),
            'fakeRoutes' => $this->shape($this->fakeRoutes()),
        ]);
        $helperImport = '';
        if ($usedHelpers !== []) {
            $names = array_keys($usedHelpers);
            sort($names);
            $helperImport = 'import type { '.implode(', ', $names)." } from \"@sti3bas/rehearsal\";\n";
        }
        $contents = "// Generated by rehearsal:types.\n{$helperImport}import \"@sti3bas/rehearsal\";\n\ndeclare module \"@sti3bas/rehearsal\" {\n  interface RehearsalSchema $schema\n}\n";
        if (file_put_contents($path, $contents) === false) {
            $this->error("Could not write $path.");

            return self::FAILURE;
        }

        $this->info("Generated $path.");

        return self::SUCCESS;
    }

    /**
     * @param  array<string, array{method: string, params: list<array{name: string, optional: bool, nullable: bool, types: list<array{kind: string, class?: string}>}>}>  $states
     * @param  list<string>  $definitionKeys
     * @param  array<string, string>  $aliasesByClass
     * @param  array<string, true>  $usedHelpers
     */
    private function factory(array $definition, array $states, array $definitionKeys, array $aliasesByClass, array &$usedHelpers): string
    {
        $class = $definition['model'];
        /** @var Model $model */
        $model = new $class;
        $defaults = $model->getAttributes();
        $attributes = array_fill_keys(array_unique([
            ...$model->getFillable(),
            ...array_keys($defaults),
        ]), 'unknown');
        foreach ($model->getDates() as $column) {
            $attributes[$column] = 'string | null';
        }
        $columns = $this->columns($model);
        foreach ($columns ?? [] as $column) {
            $type = $this->columnType(strtolower($column['type_name']));
            $attributes[$column['name']] = $column['nullable'] ? "$type | null" : $type;
        }
        $columnNames = $columns === null ? null : array_column($columns, 'name');
        $attributes[$model->getKeyName()] = $this->phpType($model->getKeyType());
        preg_match_all('/(@property(?:-read|-write)?)\s+(\S+)\s+\$(\w+)/', (new \ReflectionClass($model))->getDocComment() ?: '', $properties, PREG_SET_ORDER);
        $fallbackColumns = array_fill_keys([...array_keys($attributes), ...array_keys($model->getCasts())], true);
        $knownCasts = [];
        foreach ($model->getCasts() as $attribute => $cast) {
            [$name, $argument] = array_pad(explode(':', $cast, 2), 2, null);
            $type = match ($name) {
                'date', 'datetime', 'immutable_date', 'immutable_datetime', 'hashed' => 'string',
                'encrypted' => match ($argument) {
                    null => 'string',
                    'array', 'json', 'collection' => $this->phpType('array'),
                    'object' => 'Record<string, unknown>',
                    default => 'unknown',
                },
                'timestamp' => 'number',
                'collection' => $this->phpType('array'),
                default => $this->phpType($name),
            };
            if ($type !== 'unknown') {
                $knownCasts[$attribute] = true;
                $attributes[$attribute] = $attribute === $model->getKeyName() ? $type : "$type | null";
            }
        }

        $input = $attributes + array_fill_keys($definitionKeys, 'unknown');
        $appends = array_fill_keys($model->getAppends(), 'unknown');
        $output = $attributes + $appends;
        foreach ($definitionKeys as $attribute) {
            if (! isset($appends[$attribute]) && (
                ($columnNames !== null && ! in_array($attribute, $columnNames, true))
                || ($columnNames === null && ! array_key_exists($attribute, $defaults) && $this->hasAttributeMutator($model, $attribute))
            )) {
                unset($output[$attribute]);
            }
        }
        foreach ($properties as [, $annotation, $type, $attribute]) {
            $writeOnly = $annotation === '@property-write';
            if ($annotation === '@property'
                || ($annotation === '@property-read' && ($model->hasSetMutator($attribute) || $model->hasAttributeSetMutator($attribute)))) {
                $fallbackColumns[$attribute] = true;
            }
            if ($writeOnly || (! isset($knownCasts[$attribute]) && $annotation !== '@property-read')) {
                $input[$attribute] = $this->phpType($type);
            }
            if (! $writeOnly && ! isset($knownCasts[$attribute])) {
                $output[$attribute] = $this->phpType($type);
            }
        }
        $filterColumns = $columnNames ?? array_keys(array_diff_key($fallbackColumns, $appends));
        $filters = array_intersect_key($output, array_flip($filterColumns));
        $output = array_diff_key($output, array_flip($model->getHidden()));
        if ($model->getVisible() !== []) {
            $output = array_intersect_key($output, array_flip($model->getVisible()));
        }
        $types = $definition['types'] ?? [];
        $input = array_replace($input, $types['attributes'] ?? []);
        $output = array_replace($output, $types['model'] ?? []);
        $required = array_intersect_key($output, array_flip([$model->getKeyName(), ...($types['required'] ?? [])]));
        $definitionKeys = array_filter(
            array_intersect($definitionKeys, $columnNames ?? array_keys($defaults)),
            fn (string $attribute) => ! $this->hasAttributeMutator($model, $attribute),
        );
        $factoryRequired = array_intersect_key(array_diff_key($output, $required), array_flip($definitionKeys));

        $stateShapes = [];
        foreach ($states as $stateName => $stateDef) {
            $stateShapes[$stateName] = $this->stateTuple($stateDef['params'], $aliasesByClass, $usedHelpers);
        }

        return $this->shape([
            'attributes' => $this->shape([], $input),
            'model' => $this->shape($required, array_diff_key($output, $required)),
            'modelFilters' => $this->shape([], $filters),
            ...($factoryRequired === [] ? [] : ['factoryRequired' => $this->literals(array_keys($factoryRequired))]),
            'modelColumns' => $this->literals($filterColumns),
            'states' => $this->shape($stateShapes),
            'relations' => $this->shape(array_map($this->literal(...), $definition['relations'] ?? [])),
        ]);
    }

    private function hasAttributeMutator(Model $model, string $attribute): bool
    {
        return $model->hasSetMutator($attribute) || $model->hasAttributeMutator($attribute);
    }

    private function columns(Model $model): ?array
    {
        $table = $model->getTable();
        $database = $this->option('database');
        if (is_string($database) && $database !== '') {
            return Schema::connection($database)->getColumns($table) ?: null;
        }

        try {
            $schema = Schema::connection($model->getConnectionName());
            if ($schema->hasTable($table)) {
                return $schema->getColumns($table);
            }
        } catch (Throwable) {
        }

        $ephemeral = $this->inMemorySchemaConnection();
        if ($ephemeral !== null) {
            try {
                $schema = Schema::connection($ephemeral);
                if ($schema->hasTable($table)) {
                    return $schema->getColumns($table);
                }
            } catch (Throwable) {
            }
        }

        return null;
    }

    /**
     * @param  list<array{name: string, optional: bool, nullable: bool, types: list<array{kind: string, class?: string}>}>  $params
     * @param  array<string, string>  $aliasesByClass
     * @param  array<string, true>  $usedHelpers
     */
    private function stateTuple(array $params, array $aliasesByClass, array &$usedHelpers): string
    {
        if ($params === []) {
            return '[]';
        }
        $trailingOptionalFrom = count($params);
        for ($i = count($params) - 1; $i >= 0; $i--) {
            if (! $params[$i]['optional']) {
                break;
            }
            $trailingOptionalFrom = $i;
        }
        $elements = [];
        foreach ($params as $index => $param) {
            $parts = [];
            foreach ($param['types'] as $type) {
                $parts[] = match ($type['kind']) {
                    'string' => 'string',
                    'int', 'float' => 'number',
                    'bool' => 'boolean',
                    'true' => 'true',
                    'false' => 'false',
                    'array' => 'unknown[] | Record<string, unknown>',
                    'date' => 'string | Date',
                    'enum' => $this->phpType($type['class']),
                    'model' => $this->modelParamType($type['class'], $aliasesByClass, $usedHelpers),
                    default => 'unknown',
                };
            }
            if ($param['nullable']) {
                $parts[] = 'null';
            }
            $tsType = implode(' | ', array_unique($parts));
            $opt = $index >= $trailingOptionalFrom ? '?' : '';
            $elements[] = "{$param['name']}{$opt}: {$tsType}";
        }

        return '['.implode(', ', $elements).']';
    }

    /**
     * @param  array<string, string>  $aliasesByClass
     * @param  array<string, true>  $usedHelpers
     */
    private function modelParamType(string $class, array $aliasesByClass, array &$usedHelpers): string
    {
        if ($class === Model::class) {
            $usedHelpers['FactoryModelRef'] = true;
            $usedHelpers['FactoryName'] = true;

            return 'FactoryModelRef<FactoryName>';
        }
        if (isset($aliasesByClass[$class])) {
            $usedHelpers['FactoryModelRef'] = true;

            return 'FactoryModelRef<'.$this->literal($aliasesByClass[$class]).'>';
        }

        return '{ id: number | string }';
    }

    private function ruleShape(array $rules): string
    {
        $required = $optional = [];
        foreach ($rules as $field => $fieldRules) {
            if (str_contains($field, '.')) {
                continue;
            }
            $names = array_map(static fn ($rule) => is_string($rule) ? explode(':', $rule, 2)[0] : '', is_array($fieldRules) ? $fieldRules : explode('|', $fieldRules));
            $type = match (true) {
                in_array('boolean', $names, true) => 'boolean',
                in_array('string', $names, true) => 'string',
                in_array('integer', $names, true), in_array('numeric', $names, true) => 'number',
                in_array('list', $names, true) => 'unknown[]',
                in_array('array', $names, true) => 'unknown[] | Record<string, unknown>',
                default => 'unknown',
            };
            if (in_array('nullable', $names, true)) {
                $type .= ' | null';
            }
            if (in_array('required', $names, true) || in_array('present', $names, true)) {
                $required[$field] = $type;
            } else {
                $optional[$field] = $type;
            }
        }

        return $required === [] && $optional === [] ? 'Record<string, never>' : $this->shape($required, $optional);
    }

    private function phpType(string $type): string
    {
        if (str_starts_with($type, '?')) {
            return $this->phpType(substr($type, 1)).' | null';
        }
        if (str_contains($type, '|')) {
            return implode(' | ', array_unique(array_map($this->phpType(...), explode('|', $type))));
        }
        if (str_ends_with($type, '[]')) {
            return '('.$this->phpType(substr($type, 0, -2)).')[]';
        }
        if (is_a($type, BackedEnum::class, true)) {
            return $this->literals(array_map(static fn (BackedEnum $case) => $case->value, $type::cases()));
        }

        return match (strtolower($type)) {
            'bool', 'boolean' => 'boolean',
            'int', 'integer', 'float', 'double', 'real', 'number' => 'number',
            'string', 'decimal' => 'string',
            'null', 'void' => 'null',
            'true', 'false' => $type,
            'array', 'json', 'object' => 'unknown[] | Record<string, unknown>',
            default => 'unknown',
        };
    }

    /**
     * @param  array<string, mixed>  $rules
     * @param  array<class-string, string>  $aliasesByClass
     * @param  array<string, true>  $usedHelpers
     */
    private function operationInput(
        ReflectionFunction|ReflectionMethod $reflection,
        array $rules,
        array $aliasesByClass,
        array &$usedHelpers,
    ): string {
        if ($rules !== []) {
            return $this->ruleShape($rules);
        }

        $params = $reflection->getParameters();
        if ($params === []) {
            return 'Record<string, never>';
        }

        if (Operations::usesPayloadArray($reflection, $rules)) {
            $docType = PhpDocTypes::paramDocType($params[0], $reflection, $aliasesByClass, $usedHelpers);

            return $docType !== null && $docType !== 'unknown' ? $docType : 'Record<string, never>';
        }

        $fields = [];
        foreach ($params as $param) {
            $optional = $param->isDefaultValueAvailable() || $param->allowsNull();
            $tsType = PhpDocTypes::paramType($param, $reflection, $aliasesByClass, $usedHelpers);
            $key = json_encode($param->getName(), JSON_THROW_ON_ERROR);
            $fields[] = $key.($optional ? '?' : '').': '.$tsType;
        }

        return '{ '.implode('; ', $fields).' }';
    }

    /** @return array<string, string> */
    private function artisanTypes(): array
    {
        $configured = config('rehearsal.artisan', []);
        $discover = $configured === true || (is_array($configured) && ($configured['discover'] ?? false) === true);
        $artisan = [];
        if ($discover) {
            foreach (array_keys(Artisan::all()) as $name) {
                $artisan[$name] = 'Record<string, unknown>';
            }
        }
        if (is_array($configured)) {
            foreach ($configured as $name => $definition) {
                if ($name === 'discover' && is_bool($definition)) {
                    continue;
                }
                if ($definition === false) {
                    unset($artisan[$name]);

                    continue;
                }
                if (is_array($definition)) {
                    $artisan[$name] = $definition['types']['input'] ?? $this->ruleShape($definition['rules'] ?? []);
                }
            }
        }
        ksort($artisan);

        return $artisan;
    }

    /** @return array<string, string> */
    private function fakeRoutes(): array
    {
        $configured = config('rehearsal.fake_response_types', []);
        $routes = [];
        foreach (FakeRoutes::keys() as $route) {
            $type = $configured[$route] ?? null;
            $routes[$route] = is_string($type) ? $type : 'unknown';
        }

        return $routes;
    }

    private function inMemorySchemaConnection(): ?string
    {
        if ($this->inMemorySchemaAttempted) {
            return $this->inMemorySchema;
        }
        $this->inMemorySchemaAttempted = true;

        $migrationsPath = database_path('migrations');
        if (! is_dir($migrationsPath)) {
            return null;
        }

        $connection = 'rehearsal_types_schema';
        $memoryConfig = [
            'driver' => 'sqlite',
            'database' => ':memory:',
            'prefix' => '',
            'foreign_key_constraints' => false,
        ];
        $originalConnections = config('database.connections', []);
        $sandboxed = [$connection => $memoryConfig];
        $sandboxedNames = [];
        foreach (is_array($originalConnections) ? $originalConnections : [] as $name => $cfg) {
            if (is_array($cfg) && ($cfg['driver'] ?? null) === 'sqlite' && ($cfg['database'] ?? null) === ':memory:') {
                $sandboxed[$name] = $cfg;

                continue;
            }
            $sandboxed[$name] = $memoryConfig;
            $sandboxedNames[] = $name;
            DB::purge($name);
        }
        config(['database.connections' => $sandboxed]);

        try {
            $exit = Artisan::call('migrate', [
                '--database' => $connection,
                '--force' => true,
            ]);
            if ($exit === 0) {
                $this->inMemorySchema = $connection;
            }
        } catch (Throwable) {
            return null;
        } finally {
            $restored = is_array($originalConnections) ? $originalConnections : [];
            $restored[$connection] = $memoryConfig;
            config(['database.connections' => $restored]);
            foreach ($sandboxedNames as $name) {
                DB::purge($name);
            }
        }

        return $this->inMemorySchema;
    }

    private function columnType(string $type): string
    {
        return match (true) {
            str_contains($type, 'bool') => 'boolean',
            preg_match('/int|float|double|real|serial/', $type) === 1 => 'number',
            preg_match('/char|text|date|time|uuid|decimal|numeric|enum/', $type) === 1 => 'string',
            default => 'unknown',
        };
    }

    private function shape(array $required, array $optional = []): string
    {
        ksort($required);
        ksort($optional);
        $members = [];
        foreach ($required as $key => $type) {
            $members[] = $this->literal($key).": $type;";
        }
        foreach ($optional as $key => $type) {
            $members[] = $this->literal($key)."?: $type;";
        }

        return $members === [] ? '{}' : '{ '.implode(' ', $members).' }';
    }

    private function literals(array $values): string
    {
        return $values === [] ? 'never' : implode(' | ', array_map($this->literal(...), $values));
    }

    private function literal(string|int $value): string
    {
        return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
    }
}
